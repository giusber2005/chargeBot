document.addEventListener('DOMContentLoaded', () => {

    //demo mode slider: the choice is stored in a cookie the server reads on every chat request
    const demoToggle = document.getElementById('demoToggle');
    if (demoToggle && !demoToggle.disabled) {
        demoToggle.checked = document.cookie.split('; ').includes('demo=1');
        demoToggle.addEventListener('change', () => {
            const maxAge = demoToggle.checked ? 60 * 60 * 24 * 30 : 0;
            document.cookie = `demo=1; path=/; max-age=${maxAge}; SameSite=Lax`;
        });
    }

    function escapeHtml(text) {
        const div = document.createElement('div');
        div.textContent = text;
        return div.innerHTML;
    }

    // ---------------------------------------------------------------- chat

    const chatMessages = document.getElementById('chatMessages');

    function appendMessage(html, user) {
        const messageDiv = document.createElement('div');
        messageDiv.className = `message ${user ? 'user' : 'other'}`;
        messageDiv.innerHTML = html;
        chatMessages.appendChild(messageDiv);
        chatMessages.scrollTop = chatMessages.scrollHeight; // Scroll to the bottom
        return messageDiv;
    }

    // user text is escaped, the bot answers are HTML generated by the server
    function addMessage(text, user = true) {
        return appendMessage(`<div class="message-text">${user ? escapeHtml(text) : text}</div>`, user);
    }

    function addAudioMessage(src, user = true) {
        return appendMessage(`<div class="message-text message-audio"><audio controls src="${src}"></audio></div>`, user);
    }

    function addTypingIndicator() {
        return appendMessage('<div class="message-text typing"><span></span><span></span><span></span></div>', false);
    }

    if (chatMessages) {
        fetch('/check-database')
        .then(response => response.json())
        .then(data => {
            if (data.error) {
                console.error('Error:', data.error);
                return;
            }
            data.forEach(entry => {
                const user = entry.user || 'N/A';
                if (user.endsWith('.wav')) {
                    addAudioMessage(`/audio_folder/${encodeURIComponent(user)}`, true);
                } else {
                    addMessage(user, true);
                }
                addMessage(entry.machine || 'N/A', false);
            });
        })
        .catch(error => console.error('Error:', error));
    }

    const composer = document.getElementById('composer');
    const messageInput = composer.querySelector('.composer-input');
    const sendButton = document.getElementById('sendButton');
    const recordButton = document.getElementById('recordButton');

    function setBusy(busy) {
        sendButton.disabled = busy;
        recordButton.disabled = busy;
        document.getElementById('sendAudioButton').disabled = busy;
    }

    // Send a question (text or audio) to the route of the page: the homepage redirects to the chat,
    // the chat page answers with the bot message
    function sendQuestion(formData) {
        setBusy(true);
        const typing = chatMessages ? addTypingIndicator() : null;

        fetch(composer.dataset.route, { method: 'POST', body: formData })
        .then(response => {
            if (!response.ok) {
                throw new Error('Network response was not ok');
            }
            return response.json();
        })
        .then(data => {
            if (data.redirect) {
                window.location.href = data.redirect;
            } else if (data.message) {
                addMessage(data.message, false);
            }
        })
        .catch(error => {
            console.error('Error:', error);
            if (chatMessages) {
                addMessage('<p>Sorry, something went wrong. Please try again.</p>', false);
            }
        })
        .finally(() => {
            if (typing) typing.remove();
            setBusy(false);
        });
    }

    composer.addEventListener('submit', event => {
        event.preventDefault();
        const text = messageInput.value.trim();
        if (!text) return;

        const formData = new FormData();
        formData.append(messageInput.name, text);
        if (chatMessages) {
            addMessage(text, true);
            messageInput.value = '';
        }
        sendQuestion(formData);
    });

    document.querySelectorAll('[data-suggestion]').forEach(chip => {
        chip.addEventListener('click', () => {
            messageInput.value = chip.dataset.suggestion;
            composer.requestSubmit();
        });
    });

    // ---------------------------------------------------------------- voice messages

    const recorder = document.getElementById('recorder');
    const recorderLive = document.getElementById('recorderLive');
    const recorderReview = document.getElementById('recorderReview');
    const audioPlayer = document.getElementById('audioPlayer');
    const recordTimer = document.getElementById('recordTimer');
    let mediaRecorder;
    let recordedFile = null;
    let timerId;

    function resetRecorder() {
        recorder.hidden = true;
        recordedFile = null;
        audioPlayer.removeAttribute('src');
        audioPlayer.load();
    }

    async function startRecording() {
        let audioChunks = [];
        try {
            const stream = await navigator.mediaDevices.getUserMedia({ audio: true });
            mediaRecorder = new MediaRecorder(stream);
        } catch (error) {
            console.error('Error accessing microphone:', error);
            alert('The microphone is not available.');
            return;
        }

        recorder.hidden = false;
        recorderLive.hidden = false;
        recorderReview.hidden = true;

        const startedAt = Date.now();
        recordTimer.textContent = '0:00';
        timerId = setInterval(() => {
            const seconds = Math.floor((Date.now() - startedAt) / 1000);
            recordTimer.textContent = `${Math.floor(seconds / 60)}:${String(seconds % 60).padStart(2, '0')}`;
        }, 250);

        mediaRecorder.ondataavailable = event => audioChunks.push(event.data);
        mediaRecorder.onstop = () => {
            clearInterval(timerId);
            mediaRecorder.stream.getTracks().forEach(track => track.stop());

            const audioBlob = new Blob(audioChunks, { type: 'audio/wav' });
            const filename = 'recordedAudio_' + Math.random().toString(36).substr(2, 8) + '.wav';
            recordedFile = new File([audioBlob], filename, { type: 'audio/wav' });

            audioPlayer.src = URL.createObjectURL(audioBlob);
            recorderLive.hidden = true;
            recorderReview.hidden = false;
        };

        mediaRecorder.start();
    }

    recordButton.addEventListener('click', startRecording);
    document.getElementById('againButton').addEventListener('click', startRecording);
    document.getElementById('delButton').addEventListener('click', resetRecorder);

    document.getElementById('stopButton').addEventListener('click', () => {
        if (mediaRecorder && mediaRecorder.state === 'recording') {
            mediaRecorder.stop();
        }
    });

    document.getElementById('sendAudioButton').addEventListener('click', () => {
        if (!recordedFile) return;
        const formData = new FormData();
        formData.append('audioStorage', recordedFile);
        if (chatMessages) {
            addAudioMessage(audioPlayer.src, true);
        }
        recorder.hidden = true;
        sendQuestion(formData);
    });

    // ---------------------------------------------------------------- charging session

    const STATUS_LABELS = { preparing: 'Connecting', charging: 'Charging', complete: 'Complete', stopped: 'Stopped' };
    const RING_LENGTH = 2 * Math.PI * 52;
    const statusHolders = document.querySelectorAll('.charge-chip, .charge-summary, .charging-panel');
    const socRing = document.getElementById('socRing');
    const socTarget = document.getElementById('socTarget');
    const summaryFill = document.getElementById('summaryFill');
    const stopCharging = document.getElementById('stopCharging');
    const restartCharging = document.getElementById('restartCharging');

    function formatDuration(seconds) {
        const h = Math.floor(seconds / 3600);
        const m = Math.floor((seconds % 3600) / 60);
        const s = seconds % 60;
        return h ? `${h}:${String(m).padStart(2, '0')}:${String(s).padStart(2, '0')}` : `${m}:${String(s).padStart(2, '0')}`;
    }

    function formatRemaining(data) {
        if (data.status === 'complete') return 'Done';
        if (data.status === 'stopped') return 'Stopped';
        const minutes = Math.ceil(data.remaining_s / 60);
        if (minutes < 1) return '< 1 min';
        if (minutes < 60) return `${minutes} min`;
        return `${Math.floor(minutes / 60)} h ${String(minutes % 60).padStart(2, '0')} min`;
    }

    function formatFinish(data) {
        if (data.status === 'complete') return `Charged to ${data.target_soc}%, you can unplug`;
        if (data.status === 'stopped') return 'Session stopped';
        const finish = new Date(Date.now() + data.remaining_s * 1000);
        return `Ready at ${finish.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })}`;
    }

    const euro = new Intl.NumberFormat(undefined, { style: 'currency', currency: 'EUR' });

    function setField(name, value) {
        document.querySelectorAll(`[data-field="${name}"]`).forEach(element => {
            element.textContent = value;
        });
    }

    function renderCharging(data) {
        statusHolders.forEach(holder => holder.dataset.status = data.status);

        setField('status', STATUS_LABELS[data.status]);
        setField('soc', `${Math.round(data.soc)}%`);
        setField('soc_number', Math.round(data.soc));
        setField('target', `${data.target_soc}%`);
        setField('remaining', formatRemaining(data));
        setField('finish', formatFinish(data));
        setField('power', data.power_kw.toFixed(1));
        setField('energy', data.energy_kwh.toFixed(2));
        setField('cost', euro.format(data.cost));
        setField('price', euro.format(data.price_per_kwh));
        setField('range', data.range_added_km);
        setField('elapsed', formatDuration(data.elapsed_s));
        setField('voltage', data.voltage_v);
        setField('current', data.current_a);
        setField('temp', data.battery_temp_c.toFixed(1));
        setField('start_soc', Math.round(data.start_soc));
        setField('charger', data.station.charger_id);
        setField('connector', data.station.connector);
        setField('max_power', data.station.max_power_kw);

        if (socRing) {
            socRing.style.strokeDashoffset = RING_LENGTH * (1 - data.soc / 100);
            // the svg is rotated by -90deg, so angle 0 is the top of the ring
            const angle = data.target_soc / 100 * 360;
            socTarget.setAttribute('x1', 104);
            socTarget.setAttribute('x2', 120);
            socTarget.setAttribute('y1', 60);
            socTarget.setAttribute('y2', 60);
            socTarget.setAttribute('transform', `rotate(${angle} 60 60)`);
        }
        if (summaryFill) {
            summaryFill.style.width = `${data.soc}%`;
        }
        if (stopCharging) {
            const active = data.status === 'preparing' || data.status === 'charging';
            stopCharging.hidden = !active;
            restartCharging.hidden = active;
        }
        renderPowerChart(data);
    }

    // Single-series area chart of the charging power, with a crosshair tooltip on hover
    const powerChart = document.getElementById('powerChart');
    let chartPoints = [];

    function renderPowerChart(data) {
        if (!powerChart) return;
        chartPoints = data.history;
        if (chartPoints.length < 2) {
            powerChart.innerHTML = '<p class="muted small chart-empty">The power curve appears once charging starts.</p>';
            return;
        }

        const width = powerChart.clientWidth;
        const height = powerChart.clientHeight;
        const pad = { left: 30, right: 6, top: 8, bottom: 18 };
        const maxPower = data.station.max_power_kw;
        const maxTime = Math.max(chartPoints[chartPoints.length - 1].t, 300);
        const x = t => pad.left + t / maxTime * (width - pad.left - pad.right);
        const y = p => pad.top + (1 - p / maxPower) * (height - pad.top - pad.bottom);

        let svg = `<svg viewBox="0 0 ${width} ${height}" role="img" aria-label="Charging power over time">
            <defs><linearGradient id="powerGradient" x1="0" x2="0" y1="0" y2="1">
                <stop offset="0%" stop-color="#2fd4a0" stop-opacity="0.35"/>
                <stop offset="100%" stop-color="#2fd4a0" stop-opacity="0"/>
            </linearGradient></defs>`;

        for (let p = 0; p <= maxPower; p += 50) {
            svg += `<line class="chart-grid" x1="${pad.left}" x2="${width - pad.right}" y1="${y(p)}" y2="${y(p)}"/>
                    <text class="chart-axis" x="${pad.left - 6}" y="${y(p) + 3}" text-anchor="end">${p}</text>`;
        }
        const minuteStep = Math.max(1, Math.ceil(maxTime / 60 / 5));
        for (let m = 0; m * 60 <= maxTime; m += minuteStep) {
            svg += `<text class="chart-axis" x="${x(m * 60)}" y="${height - 4}" text-anchor="middle">${m}m</text>`;
        }

        const line = chartPoints.map(point => `${x(point.t).toFixed(1)},${y(point.power).toFixed(1)}`).join(' ');
        const first = chartPoints[0];
        const last = chartPoints[chartPoints.length - 1];
        svg += `<polygon class="chart-area" points="${x(first.t)},${y(0)} ${line} ${x(last.t)},${y(0)}"/>
                <polyline class="chart-line" points="${line}"/>
                <g class="chart-hover" visibility="hidden">
                    <line class="chart-cross" y1="${pad.top}" y2="${height - pad.bottom}"/>
                    <circle class="chart-dot" r="5"/>
                </g>
            </svg>
            <div class="chart-tooltip" hidden></div>`;
        powerChart.innerHTML = svg;

        const hover = powerChart.querySelector('.chart-hover');
        const tooltip = powerChart.querySelector('.chart-tooltip');
        const svgElement = powerChart.querySelector('svg');

        svgElement.addEventListener('pointermove', event => {
            const rect = svgElement.getBoundingClientRect();
            const px = event.clientX - rect.left;
            const nearest = chartPoints.reduce((best, point) =>
                Math.abs(x(point.t) - px) < Math.abs(x(best.t) - px) ? point : best);
            const cx = x(nearest.t);
            hover.setAttribute('visibility', 'visible');
            hover.querySelector('line').setAttribute('x1', cx);
            hover.querySelector('line').setAttribute('x2', cx);
            hover.querySelector('circle').setAttribute('cx', cx);
            hover.querySelector('circle').setAttribute('cy', y(nearest.power));
            tooltip.hidden = false;
            tooltip.style.left = `${Math.min(Math.max(cx, 70), width - 70)}px`;
            tooltip.textContent = `${formatDuration(nearest.t)} · ${nearest.power.toFixed(1)} kW · ${Math.round(nearest.soc)}%`;
        });
        svgElement.addEventListener('pointerleave', () => {
            hover.setAttribute('visibility', 'hidden');
            tooltip.hidden = true;
        });
    }

    function pollCharging() {
        // skip the redraw while the user is reading the chart tooltip
        if (powerChart && powerChart.matches(':hover')) return;
        fetch('/charging-status')
        .then(response => response.json())
        .then(renderCharging)
        .catch(error => console.error('Error:', error));
    }

    function chargingAction(route) {
        fetch(route, { method: 'POST' })
        .then(response => response.json())
        .then(renderCharging)
        .catch(error => console.error('Error:', error));
    }

    if (stopCharging) {
        stopCharging.addEventListener('click', () => {
            if (confirm('Stop charging now? You will be billed for the energy delivered so far.')) {
                chargingAction('/charging/stop');
            }
        });
        restartCharging.addEventListener('click', () => chargingAction('/charging/restart'));
    }

    pollCharging();
    setInterval(pollCharging, 2000);

    // ---------------------------------------------------------------- inactivity

    // Back to the homepage (which resets the chat) after 15 minutes without any interaction
    let inactivityId;

    function startOrResetInterval() {
        clearTimeout(inactivityId);
        inactivityId = setTimeout(() => window.location.replace('/'), 15 * 60 * 1000);
    }

    ['keydown', 'pointerdown', 'touchstart', 'wheel'].forEach(name => {
        document.addEventListener(name, startOrResetInterval, { passive: true });
    });

    startOrResetInterval();
});
